/**
 * Классы автомобилей.
 *
 * Класс — одна из категорий, по которым клиент выбирает машину на странице
 * «Автомобили». Рядом с классами там же стоят марки: их список собирается
 * из самих автомобилей (см. `catalog-filters.ts`).
 *
 * У каждого класса есть своя страница — на неё ведут объявления и реклама,
 * поэтому здесь же лежат тексты: что это за класс и на что в нём смотреть.
 */

export type CarClassId = "premium" | "luxury" | "exclusive";

export interface CarClass {
  id: CarClassId;
  /** Название категории в фильтре. */
  label: string;
  /** Короткая подпись: какие марки попадают в класс. */
  hint: string;
  /** Адрес страницы класса. */
  path: string;
  /** Заголовок страницы: первая строка обычная, вторая — курсивом. */
  heading: [string, string];
  /** Абзац под заголовком. */
  intro: string;
  /** На что смотреть в этом классе. */
  points: string[];
}

